// Regenerates material-icons.txt from MonoCode's icon package:
//
//   node assets/file-icons/generate.mjs \
//     reference/monocode/node_modules/react-material-icon-theme/dist/index.esm.js
//
// The package's own lookups fill the tables, so BenCode resolves a name to
// the icon MonoCode shows. Only what those tables can reach is kept: no
// `_light` variants (MonoCode never asks for them), no root-folder icons,
// and no names MonoCode's lowercased file lookup cannot match.
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const source = process.argv[2];
if (!source) {
  console.error("usage: node generate.mjs <react-material-icon-theme/dist/index.esm.js>");
  process.exit(1);
}
const pack = await import(pathToFileURL(resolve(source)).href);

const plain = (key) => !/[\t\n/]/.test(key);
// A few icons are recolours the package names but ships no SVG for; MonoCode
// draws a blank there, BenCode falls through to the next match instead.
const drawn = (icon) => (icon && pack.getIconSvg(icon) ? icon : "");
const fileIcon = (query) => drawn(pack.getFileIcon({ ...query, fallback: "", iconPack: "" }));

// MonoCode `resolveFileIcon` lowercases the name before asking.
const names = new Map();
for (const name of pack.getAvailableFileNames()) {
  const icon = plain(name) && name === name.toLowerCase() && fileIcon({ fileName: name });
  if (icon) names.set(name, icon);
}
const extensions = new Map();
for (const ext of pack.getAvailableFileExtensions()) {
  const icon = plain(ext) && ext === ext.toLowerCase() && fileIcon({ fileExtension: ext });
  if (icon) extensions.set(ext, icon);
}
const folders = new Map();
for (const name of pack.getAvailableFolderNames()) {
  const icon = plain(name) && drawn(pack.getFolderIcon({ folderName: name }));
  if (icon && icon !== "folder" && drawn(`${icon}-open`)) folders.set(name, icon);
}

const used = new Set(["file", "folder", "folder-open", ...names.values(), ...extensions.values()]);
for (const icon of folders.values()) {
  used.add(icon);
  used.add(`${icon}-open`);
}

// GPUI rasterises an SVG image at twice its own size, whatever the size it
// is drawn at, so every icon is declared 16px: sharp on a Retina display,
// and a 1024-unit viewBox does not become a 2048px bitmap.
const sized = (svg) =>
  svg.replace(/<svg\b([^>]*)>/, (_, attrs) => {
    const rest = attrs.replace(/\s(?:width|height)="[^"]*"/g, "");
    return `<svg width="16" height="16"${rest}>`;
  });

const lines = [
  "# Material Icon Theme, from react-material-icon-theme (MIT, see LICENSE).",
  "# Generated by generate.mjs; do not edit.",
  "# I icon svg | N file-name icon | E extension icon | D folder-name icon",
];
for (const icon of [...used].sort()) {
  const svg = pack.getIconSvg(icon);
  if (!svg) throw new Error(`no svg for ${icon}`);
  if (/[\t\n]/.test(svg)) throw new Error(`${icon} has a tab or newline`);
  lines.push(`I\t${icon}\t${sized(svg)}`);
}
const table = (tag, map) => {
  for (const [key, icon] of [...map].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    lines.push(`${tag}\t${key}\t${icon}`);
  }
};
table("N", names);
table("E", extensions);
table("D", folders);

const out = join(dirname(fileURLToPath(import.meta.url)), "material-icons.txt");
writeFileSync(out, `${lines.join("\n")}\n`);
console.log(
  `${used.size} icons, ${names.size} names, ${extensions.size} extensions, ${folders.size} folders -> ${out}`,
);
